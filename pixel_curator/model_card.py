"""Phase 3: professional model card generator for training runs.

Builds a publish-ready Markdown model card from everything the studio
knows about a run: run metadata, training preset, dataset lineage,
evaluation results (when `pixel-curator eval --run` has been executed),
smart stack recommendations, artistic prompt patterns and
reproducibility notes.  Missing pieces degrade to clear placeholders -
old runs without Phase 3 evaluation data still produce a useful card.

Saved to runs/<run_name>/model_card.md (or --output).  The legacy
registry card (`pixel-curator card <lora-name>`) is untouched.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional

from . import manifest
from .config import Project
from .util import now_iso


def _run_row(conn, run_name: str) -> Optional[dict]:
    from .eval.run_eval import _run_row
    return _run_row(conn, run_name)


def _dataset_line(conn, version: int) -> str:
    row = conn.execute(
        "SELECT recipe_name, content_hash, image_count, val_count, "
        "built_at FROM datasets WHERE version=?", (version,)).fetchone()
    if not row:
        return f"v{version:03d}"
    return (f"v{version:03d} ({row[0]}, {row[2]} train / {row[3]} val, "
            f"hash {row[1]}, built {row[4]})")


def _stack_table(rec: Optional[dict]) -> str:
    if not rec or not rec.get("recommended_stack"):
        return ("| Stack | Weights | Use Case |\n|---|---|---|\n"
                "| Identity anchor only | 0.75-0.90 | baseline character "
                "consistency |\n")
    rows = ["| Stack | Weights | Use Case |", "|---|---|---|"]
    stack = rec["recommended_stack"]
    label = " + ".join(x["role"].replace("_", " ") for x in stack)
    weights = ", ".join(f"{x['name']} {x['weight']:.2f}" for x in stack)
    rows.append(f"| {label} | {weights} | recommended production stack "
                f"(confidence {rec.get('confidence', '-')}) |")
    for alt in rec.get("alternatives", []):
        w = ", ".join(f"{x['name']} {x['weight']:.2f}"
                      for x in alt["stack"])
        rows.append(f"| {alt['label']} | {w} | conservative alternative |")
    return "\n".join(rows) + "\n"


def generate_model_card(conn, prj: Project, output_base: Path,
                        run_name: str, output: str = "",
                        include_samples: bool = True) -> tuple[Path, str]:
    """Returns (path, markdown).  Raises KeyError for unknown runs."""
    run = _run_row(conn, run_name)
    if run is None:
        raise KeyError(f"run '{run_name}' not found - see `pixel-curator "
                       "runs`")
    evaluation = manifest.meta_get(conn, f"evaluation:{run_name}") or {}
    trig = f"{prj.trigger_token} {prj.class_word}".strip()

    try:
        from .train.presets import PRESETS
        preset_params = PRESETS.get(run["preset"], {})
    except Exception:
        preset_params = {}

    rec = None
    try:
        from .artistic.stack_recommender import recommend_best_stack
        rec = recommend_best_stack(conn, prj, run["dataset_version"])
    except Exception:
        pass

    lora_dir = Path(prj.lora_output_dir
                    or (Path(prj.output_base) / "LORA_OUTPUT")).expanduser()
    checkpoints = sorted(lora_dir.glob(f"{run_name}*.safetensors")) \
        if lora_dir.exists() else []

    # evaluation fragments (graceful when eval was never run)
    idc = evaluation.get("identity_consistency", {})
    fx = evaluation.get("flexibility", {})
    of = evaluation.get("overfit", {})
    aq = evaluation.get("artistic_quality", {})
    eval_note = ("" if evaluation else
                 "\n> Evaluation pending - run `pixel-curator eval --run "
                 f"{run_name}` to populate this section.\n")

    samples_md = ""
    if include_samples:
        grids_dir = Path(prj.output_base) / "evals"
        found = sorted(grids_dir.glob(f"**/GRID_*{run_name}*.jpg")) \
            if grids_dir.exists() else []
        found = found or (sorted((Path(output_base) / "runs" / run_name
                                  / "evaluation" / "samples").glob("*.png"))
                          if (Path(output_base) / "runs" / run_name
                              / "evaluation" / "samples").exists() else [])
        if found:
            samples_md = "\n".join(f"![sample]({p})" for p in found[:6])
        else:
            samples_md = ("_No evaluation samples generated yet - run the "
                          "eval matrix or best-epoch sweep with Forge to "
                          "add a sample grid._")

    md = f"""# Model Card: {run_name}

Generated by pixel-curator - {now_iso()}

## Overview
Professional identity-preserving LoRA trained for character consistency
and artistic figure study workflows.

## Base Model
- Base model: `{Path(prj.base_model).name if prj.base_model else '-'}`
- Training preset: `{run['preset']}`
- Dataset version: {_dataset_line(conn, run['dataset_version'])}
- Trigger words: `{trig or '-'}`

## Recommended Usage
Recommended LoRA weight: **0.75-0.90** (identity anchor role).

### Primary Prompt Pattern
```
score_9, score_8_up, score_7_up, {trig}, studio portrait,
identity-preserving composition, character consistency,
realistic rendering, sharp focus
```

### Negative Prompt Pattern
```
lowres, bad anatomy, bad hands, deformed, blurry, watermark, text,
signature, jpeg artifacts, worst quality, identity drift,
inconsistent facial structure, distorted proportions
```

## Recommended Concept Stacks
{_stack_table(rec)}
## Evaluation Summary
- Identity consistency: {idc.get('score', 'pending')} \
({idc.get('status', 'untested')}, method {idc.get('method') or 'n/a'})
- Flexibility: {fx.get('score', 'pending')} \
({fx.get('status', 'untested')}, {fx.get('tested_prompts', 0)} scored \
prompts)
- Overfit risk: {of.get('risk', 'pending')} \
(score {of.get('score', '-')})
- Artistic quality: {aq.get('score', 'pending')} \
(confidence {aq.get('confidence', '-')})
{eval_note}
## Sample Images
{samples_md}

## Training Summary
| Field | Value |
|---|---|
| Run | {run_name} (#{run['run_id']}) |
| Status | {run['status']} |
| Steps | {run['step']}/{run['total_steps']} |
| Epochs | {run['total_epochs']} |
| Final loss | {run['last_loss']} |
| Network dim/alpha | {preset_params.get('network_dim', '-')} / \
{preset_params.get('network_alpha', '-')} |
| UNet LR / TE LR | {preset_params.get('unet_lr', '-')} / \
{preset_params.get('te_lr', '-')} |
| Started / finished | {run['started_at']} / {run['finished_at'] or '-'} |
| Checkpoints | {len(checkpoints)} on disk |

## Limitations
- Identity preservation is strongest within the framing and lighting
  distribution of the training dataset; validate edge cases with the
  flexibility test grid before production use.
- Concept stacking beyond the recommended weights can erode character
  consistency - keep the identity anchor strongest and observe the
  layering warnings.
- Personal-use model: trained on private reference material; not for
  redistribution or monetization.

## Reproducibility
- Dataset: {_dataset_line(conn, run['dataset_version'])}
- Preset: `{run['preset']}` {json.dumps(preset_params) if preset_params
                              else ''}
- Command: `{(run['command'] or '-')[:400]}`
"""

    target = (Path(output).expanduser() if output
              else Path(output_base) / "runs" / run_name / "model_card.md")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(md)
    manifest.meta_set(conn, f"model_card:{run_name}",
                      {"path": str(target), "created_at": now_iso()})
    return target, md
